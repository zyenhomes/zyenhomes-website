assert.match(receiver,/verifyGuestySvix/);
assert.match(wrangler,/GUESTY_WEBHOOKS_ENABLED = "false"/);
assert.match(wrangler,/BOOKING_REQUESTS_ENABLED = "false"/);
assert.ok(!subscription.includes("console.log(token)"));
