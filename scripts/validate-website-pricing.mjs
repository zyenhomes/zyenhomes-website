import { readFileSync } from "node:fs";
import { runInNewContext } from "node:vm";
import assert from "node:assert/strict";
const html = readFileSync("rentals.html", "utf8");
const pricing = readFileSync("zyen-all-pricing.js", "utf8");
const properties = readFileSync("properties-data.js", "utf8");
new Function(pricing);
const inlineScripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(Boolean);
for (const inline of inlineScripts) new Function(inline);
assert.match(html, /id="filters"/);
assert.match(html, /id="results"/);
assert.match(html, /data-price-id/);
assert.match(html, /zyen-all-pricing\.js/);
assert.doesNotMatch(html, /<script[^>]+src="zyen-149-pricing\.js/);
assert.match(pricing, /window\.zyUpdateQuoteCards\s*=/);
assert.match(pricing, /generation !== myGeneration/);
const sandbox = {window:{}};
runInNewContext(properties,sandbox);
const ids = sandbox.window.ZYEN_PROPERTIES.map(p=>p.id);
assert.equal(ids.length,12);
assert.equal(new Set(ids).size,ids.length);
const map = JSON.parse(readFileSync("data/guesty-listing-map.json","utf8")).listings;
assert.equal(Object.keys(map).length,9);
for (const id of Object.keys(map)) assert.ok(ids.includes(id), "Missing property: "+id);
console.log("Website pricing checks passed: 12 cards, 9 mapped listings, valid JS, one pricing script.");
