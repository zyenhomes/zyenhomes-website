import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {verifyGuestySvix,receiveGuestyMessageWebhook} from "../cloudflare/guesty-webhooks.js";
const body=JSON.stringify({event:"reservation.messageSent",reservationId:"test-1"});
const key=crypto.getRandomValues(new Uint8Array(32));
const secret="whsec_"+Buffer.from(key).toString("base64");
const id="msg_test123456", stamp=String(Math.floor(Date.now()/1000));
const mac=await crypto.subtle.importKey("raw",key,{name:"HMAC",hash:"SHA-256"},false,["sign"]);
const signature=Buffer.from(await crypto.subtle.sign("HMAC",mac,new TextEncoder().encode(id+"."+stamp+"."+body))).toString("base64");
const headers=new Headers({"svix-id":id,"svix-timestamp":stamp,"svix-signature":"v1,"+signature});
assert.equal(await verifyGuestySvix(headers,body,secret),id);
assert.equal(await verifyGuestySvix(headers,body+" ",secret),null);
assert.equal(await verifyGuestySvix(new Headers({...Object.fromEntries(headers), "svix-timestamp":String(Number(stamp)-1000)}),body,secret),null);
const req=new Request("https://example.com/api/webhooks/guesty/messages",{method:"POST",headers,body});
const disabled=await receiveGuestyMessageWebhook(req,{GUESTY_WEBHOOKS_ENABLED:"false"});
assert.equal(disabled.status,503);
const cfg=readFileSync("cloudflare/wrangler.toml","utf8");
assert.match(cfg,/GUESTY_WEBHOOKS_ENABLED = "false"/);
console.log("Guesty Svix signature and fail-closed receiver tests passed");
