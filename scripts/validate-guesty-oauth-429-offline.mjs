import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {spawnSync} from "node:child_process";
const script=readFileSync("scripts/install-guesty-signing-secret.mjs","utf8");
assert.match(script,/async function authenticate\(\)/);
assert.match(script,/response\.status===429/);
assert.match(script,/stop without retry/);
assert.doesNotMatch(script,/for\(let attempt|Retry-After|setTimeout\(/);
assert.match(script,/ALLOW_NEW_GUESTY_OAUTH_TOKEN!=="true"/);
assert.match(script,/GUESTY_OPEN_API_ACCESS_TOKEN/);
const run=spawnSync(process.execPath,["scripts/install-guesty-signing-secret.mjs"],{encoding:"utf8",env:{PATH:process.env.PATH},timeout:5000});
assert.equal(run.status,1);
assert.match(run.stderr,/Explicit handoff confirmation required/);
console.log("PASS: OAuth authentication makes no automatic retries and remains approval gated.");
