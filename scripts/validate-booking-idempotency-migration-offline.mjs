import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { BOOKING_REQUEST_IDEMPOTENCY_SCHEMA } from "./guesty-booking-request-idempotency-offline.mjs";
const migration = readFileSync("cloudflare/migrations/0005_booking_request_idempotency.sql","utf8");
const normalized = text => text.replace(/--[^\\n]*/g,"").replace(/\\s+/g," ").trim().replace(/;\\s*/g,"; ");
assert.equal(normalized(migration),normalized(BOOKING_REQUEST_IDEMPOTENCY_SCHEMA));
assert.match(migration,/CREATE UNIQUE INDEX IF NOT EXISTS idx_booking_requests_idempotency_key/);
assert.match(migration,/WHERE request_idempotency_key IS NOT NULL/);
assert.doesNotMatch(migration,/DROP TABLE|DELETE FROM|INSERT INTO|UPDATE booking_requests/i);
const worker = readFileSync("cloudflare/worker.js","utf8");
assert.match(worker,/env\\.BOOKING_REQUESTS_ENABLED !== "true"/);
console.log("PASS: migration 0005 matches offline idempotency contract and is not applied.");
